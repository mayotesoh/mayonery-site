// ---- ブロックの短い書き方 ----
// 'text'            → 段落
// 'h: text'         → 見出し
// '- text'          → 箇条書き
// '! text'          → コールアウト（目立つ枠）
// '> text'          → 引用
// **太字** が使える
const rich = (s) => {
  const out = [];
  for (const part of s.split(/(\*\*[^*]+\*\*)/g)) {
    if (!part) continue;
    const b = part.startsWith('**') && part.endsWith('**');
    out.push({ type: 'text', text: { content: b ? part.slice(2, -2) : part }, annotations: { bold: b } });
  }
  return out;
};
const block = (line) => {
  if (line.startsWith('h: ')) return { object: 'block', type: 'heading_3', heading_3: { rich_text: rich(line.slice(3)) } };
  if (line.startsWith('- ')) return { object: 'block', type: 'bulleted_list_item', bulleted_list_item: { rich_text: rich(line.slice(2)) } };
  if (line.startsWith('! ')) return { object: 'block', type: 'callout', callout: { rich_text: rich(line.slice(2)), icon: { type: 'emoji', emoji: '📌' } } };
  if (line.startsWith('> ')) return { object: 'block', type: 'quote', quote: { rich_text: rich(line.slice(2)) } };
  return { object: 'block', type: 'paragraph', paragraph: { rich_text: rich(line) } };
};

