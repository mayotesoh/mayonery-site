const plain = (p) => (p ? (p.rich_text || p.title || []).map((t) => t.plain_text).join('') : '');

for (const [key, site] of Object.entries(SITES)) {
  if (ONLY && ONLY !== key) continue;
  if (!site.token) { console.log(`\n[!] ${site.label}: トークンがありません`); continue; }
  console.log(`\n========== ${site.label} ==========`);
  let cur, rows = [];
  do {
    const r = await api(site.token, '/databases/' + site.db + '/query', 'POST', { page_size: 100, start_cursor: cur });
    rows.push(...r.results);
    cur = r.has_more ? r.next_cursor : null;
  } while (cur);

  for (const [name, lines] of Object.entries(CONTENT)) {
    const row = rows.find((r) => plain(r.properties[site.nameProp]) === name);
    if (!row) { console.log(`  [!] ${name} … この DB に見つかりません（スキップ）`); continue; }
    const body = key === 'mayo' ? lines.concat(MAYO_EXTRA) : lines;
    const old = await api(site.token, '/blocks/' + row.id + '/children?page_size=100');
    console.log(`  ${name}  旧 ${(old.results || []).length} → 新 ${body.length} ブロック`);
    if (!APPLY) continue;
    for (const b of old.results || []) await api(site.token, '/blocks/' + b.id, 'PATCH', { archived: true });
    for (let i = 0; i < body.length; i += 100) {
      await api(site.token, '/blocks/' + row.id + '/children', 'PATCH', { children: body.slice(i, i + 100).map(block) });
    }
  }
}

